import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { addManual, dismissPopover, explore, fixture, latest, openFresh, tab } from './support/football-ui.ts';

test('native pickers, sync sheets, diagnostics, and sharing have screen evidence', async ui => {
  const { app, screen } = ui;
  await openFresh(ui);
  await fixture(ui, 'Empty');
  await screen.getByRole('button', /^Sync status:/).tap();
  await app.screenshot('sync-empty');
  await screen.getByRole('button', 'Done', { exact: true }).tap();
  await screen.getByTestId('add-session').tap();
  await screen.getByTestId('session-start').getByRole('button', /^\d+ \w+ \d{4}$/).tap();
  await app.screenshot('date-calendar-picker');
  await app.restart();
  await screen.getByTestId('add-session').tap();
  const timeButton = screen.getByTestId('session-start').getByRole('button', /^\d\d:\d\d$/);
  if (await timeButton.isVisible()) await timeButton.tap();
  else await screen.getByTestId('session-start').getByRole('textbox', /^\d\d:\d\d$/).tap();
  await app.screenshot('time-wheel-picker');
  await app.restart();
  await addManual(ui, 'Training', '90');
  await screen.getByRole('button', /^Sync status:/).tap();
  await app.screenshot('sync-manual-only');
  await screen.getByRole('button', 'Done', { exact: true }).tap();
  await latest(ui, 'Training.*Manual log');
  await explore(ui, 'Details');
  await screen.scrollUntilVisible(screen.getByRole('button', 'Prepare exact export', { exact: true }), { direction: 'down' });
  await screen.getByRole('button', 'Prepare exact export', { exact: true }).tap();
  await expect(screen.getByRole('button', 'Share verified package', { exact: true })).toBeVisible();
  await screen.getByRole('button', 'Share verified package', { exact: true }).getByText('Share verified package', { exact: true }).tap();
  await expect(screen.getByTestId('ActivityListView')).toBeVisible();
  await app.screenshot('native-share-sheet');
  await dismissPopover(screen, screen.getByTestId('ActivityListView'));
  await expect(screen.getByTestId('ActivityListView')).toBeHidden();
  await expect(screen.getByRole('button', 'Share verified package', { exact: true })).toBeVisible();
  await app.restart();
  await tab(screen, 'Settings').tap();
  await screen.getByRole('button', /^Appearance,/).getByText('System', { exact: true }).tap();
  await expect(screen.getByRole('button', 'Light', { exact: true })).toBeVisible();
  await app.screenshot('appearance-menu');
  await screen.getByRole('button', 'Light', { exact: true }).tap();
  await screen.getByRole('collection-view').swipe({ direction: 'down' });
  await screen.scrollUntilVisible(screen.getByRole('button', 'Watch diagnostics', { exact: true }), { direction: 'down' });
  await screen.getByRole('button', 'Watch diagnostics', { exact: true }).tap();
  await app.screenshot('watch-diagnostics-empty');
});

test('interrupted and recovered packages keep missing evidence explicit', async ui => {
  const { app, screen } = ui;
  await openFresh(ui);
  await fixture(ui, 'Worst case');
  await screen.getByRole('scroll-view').first().swipe({ direction: 'down' });
  await screen.scrollUntilVisible(screen.getByRole('button', 'See all', { exact: true }), { direction: 'down' });
  await screen.getByRole('button', 'See all', { exact: true }).tap();
  await app.screenshot('history-worst-states');
  const interrupted = screen.getByRole('button', /11-a-side.*Watch recording/).first();
  await screen.scrollUntilVisible(interrupted, { direction: 'down' });
  await interrupted.tap();
  await expect(screen.getByText('11-a-side · Watch recording', { exact: true })).toBeVisible();
  await app.screenshot('interrupted-overview');
  await explore(ui, 'Recording quality');
  await app.screenshot('interrupted-quality');
  await app.restart();
  await tab(screen, 'Sessions').tap();
  await screen.getByRole('scroll-view').first().swipe({ direction: 'down' });
  await screen.scrollUntilVisible(screen.getByRole('button', 'See all', { exact: true }), { direction: 'down' });
  await screen.getByRole('button', 'See all', { exact: true }).tap();
  const recovered = screen.getByRole('button', /Training.*Watch recording/).first();
  await screen.scrollUntilVisible(recovered, { direction: 'down' });
  await recovered.tap();
  await expect(screen.getByText('Training · Watch recording', { exact: true })).toBeVisible();
  await app.screenshot('recovered-overview');
  await explore(ui, 'Recording quality');
  await app.screenshot('recovered-quality');
});
